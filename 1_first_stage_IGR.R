# Step 7. Plot 3D exposure-lag-response surface for one example IGR
#----------------------------------------------------------------------

# For one selected IGR, we plot the full exposure-lag-response surface.
# This graph is built directly from the DLNM predictions stored in `pred`.
#
# The axes represent:
#
#   - temperature: exposure dimension;
#   - lag: delayed effect dimension;
#   - RR: relative risk centred at the IGR-specific MMT.
#

  plot(
