  ) +
  geom_line(linewidth = 1) +
  geom_hline(yintercept = 1, linetype = 2) +
  labs(
    title = paste0(
      "Lag-specific exposure-response curve - IGR ",
      igr_example,
      ", lag ",
      unique(lag_curve_example$Lag)
    ),
    x = "Temperature (°C)",
    y = "Relative Risk"
  ) +
  theme_classic()

p_lag

